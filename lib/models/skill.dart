enum SkillCategory { programming, mobileDevelopment, tools, versionControl }

class Skill {
  final String id;
  final String name;
  final double masteryPercentage;
  final SkillCategory category;
  final String? icon;
  final String? colorMetadata;
  final String? description;

  const Skill({
    required this.id,
    required this.name,
    required this.masteryPercentage,
    required this.category,
    this.icon,
    this.colorMetadata,
    this.description,
  }) : assert(
         masteryPercentage >= 0 && masteryPercentage <= 100,
         'Mastery percentage must be between 0 and 100',
       ),
       assert(name.length > 0, 'Skill name cannot be empty');
}

